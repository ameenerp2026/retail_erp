// Mutable store for development interactions
let mockLocationStore: BusinessLocationRow[] = [...MOCK_BUSINESS_LOCATIONS]

export const getMockBusinessLocations = (): BusinessLocationRow[] => {
  return [...mockLocationStore]
}

export const addMockBusinessLocation = (item: Partial<BusinessLocationRow>): BusinessLocationRow => {
  const newId = mockLocationStore.length > 0 ? Math.max(...mockLocationStore.map((l) => l.id)) + 1 : 1
  const newLocation: BusinessLocationRow = {
    id: newId,
    locationName: item.locationName || `Location ${newId}`,
    code: item.code || item.locationCode || `LOC-${String(newId).padStart(3, '0')}`,
    locationCode: item.locationCode || item.code || `LOC-${String(newId).padStart(3, '0')}`,
    parentOrganizationUnitId: item.parentOrganizationUnitId || 1,
    locationType: item.locationType || 'BRANCH',
    businessCategory: item.businessCategory || 'RETAIL',
    addressLine1: item.addressLine1 || '',
    addressLine2: item.addressLine2 || null,
    landmark: item.landmark || null,
    city: item.city || '',
    state: item.state || '',
    country: item.country || 'IN',
    pinCode: item.pinCode || '100001',
    contactPerson: item.contactPerson || 'Contact Person',
    phoneNumber: item.phoneNumber || null,
    email: item.email || null,
    emergencyContact: item.emergencyContact || null,
    linkedGSTINId: item.linkedGSTINId || 1,
    registrationType: item.registrationType || 'REGULAR',
    defaultBillingLocation: !!item.defaultBillingLocation,
    defaultStockLocation: !!item.defaultStockLocation,
    allowSales: item.allowSales ?? true,
    allowPurchase: item.allowPurchase ?? true,
    allowInventory: item.allowInventory ?? true,
    allowDispatch: item.allowDispatch ?? true,
    allowPOS: item.allowPOS ?? true,
    status: item.status || 'ACTIVE',
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  }
  mockLocationStore = [newLocation, ...mockLocationStore]
  return newLocation
}

export const updateMockBusinessLocation = (id: number, updates: Partial<BusinessLocationRow>): BusinessLocationRow => {
  mockLocationStore = mockLocationStore.map((loc) => {
    if (loc.id === id) {
      return {
        ...loc,
        ...updates,
        updatedAt: new Date().toISOString(),
      }
    }
    return loc
  })
  return mockLocationStore.find((loc) => loc.id === id)!
}

export const deleteMockBusinessLocation = (id: number): boolean => {
  const initialLen = mockLocationStore.length
  mockLocationStore = mockLocationStore.filter((loc) => loc.id !== id)
  return mockLocationStore.length < initialLen
}
